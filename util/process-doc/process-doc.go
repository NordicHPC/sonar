// Process-doc reads a valid Go package from stdin, extracts some documentation that's written in
// standard godoc format, along with type definitions, and generates various output on stdout,
// depending on options.
//
// Usage:
//
//	process-doc [options] < input-file > output-file
//
// A typical input file is ../formats/newfmt/types.go (and in fact some of the emitted text assumes
// this).  Output is markdown documentation, field name definitions to be used by Rust code, yaml to
// be used by Python code, or annotated Go source to be processed by clients' REST APIs.
//
// Options:
//
//	-doc
//	  Extract all documentation and emit markdown for format and fields
//
//	-yaml
//	  Extract all documentation and emit yaml for for format and fields
//
//	-tag
//	  Extract field names and emit Rust constant definitions for field tags (strings)
//
//	-huma
//	  Extract Go type definitions with elaborated JSON annotations to be used by a Huma REST API
//
//	-w
//	  Print warnings for likely problems.
package main

